# -*- coding: utf-8 -*-
"""آلية مطابقة التخصص (القرار النهائي المتفق عليه):
1) PDF بالاسم الصريح المعتمد (مع التطبيع العربي: عربي = اللغة العربية ...).
2) إن لم يوجد في PDF => Excel حرفيًا بدون مطابقة، مع تسجيل المصدر.
3) خلية التخصص فارغة في Excel => 'أخرى'.
"""
from .data_loader import _norm_ar

# الأسماء الصريحة المعتمدة كما وردت في ملفات PDF/المواد المقررة
PDF_EXPLICIT_SPECS = [
    "اللغة العربية", "اللغة الإنجليزية", "الرياضيات", "العلوم",
    "الفيزياء", "الكيمياء", "الأحياء", "التاريخ", "الجغرافيا",
    "التربية الإسلامية", "الحاسوب", "التربية المهنية", "الصحية والمهنية",
    "الاقتصاد المنزلي", "التربية الفنية", "التربية الرياضية", "الموسيقى",
    "الفرنسية", "علم الاجتماع", "الإحصاء", "الجيولوجيا", "الرياضة",
]

# اختيارات شائعة في Excel تُطبع إلى الاسم الصريح في PDF
_ALIAS = {
    "عربي": "اللغة العربية", "عربيه": "اللغة العربية", "لغه عربيه": "اللغة العربية",
    "لغة عربية": "اللغة العربية", "العربية": "اللغة العربية",
    "انجليزى": "اللغة الإنجليزية", "انجليزيه": "اللغة الإنجليزية",
    "لغه انجليزيه": "اللغة الإنجليزية", "إنجليزي": "اللغة الإنجليزية",
    "رياضيات": "الرياضيات", "رياضي": "الرياضيات",
    "فيزياء": "الفيزياء", "كيمياء": "الكيمياء", "احياء": "الأحياء",
    "تاريخ": "التاريخ", "جغرافيا": "الجغرافيا",
    "شرعي": "التربية الإسلامية", "تربية اسلاميه": "التربية الإسلامية",
    "حاسوب": "الحاسوب", "كمبيوتر": "الحاسوب", "تكنولوجيا المعلومات": "الحاسوب",
    "مهنى": "التربية المهنية", "تربية مهنيه": "التربية المهنية",
    "صناعي": "التربية المهنية", "تجاري": "الاقتصاد المنزلي",
    "فني": "التربية الفنية", "رياضه": "التربية الرياضية",
}

_PDF_NORM = {}
for _s in PDF_EXPLICIT_SPECS:
    _PDF_NORM[_norm_ar(_s)] = _s
    # مفاتيح إضافية بصيغة "لغه X" المطبوعة في Excel القديم
for extra, target in [("لغه عربيه", "اللغة العربية"), ("لغه انجليزيه", "اللغة الإنجليزية")]:
    _PDF_NORM.setdefault(extra, target)


def resolve_specialization(excel_spec):
    """يعيد (النهائي, المصدر) حيث المصدر في {PDF, Excel, OTHER_DEFAULT}."""
    raw = str(excel_spec or "").strip()
    if not raw:
        return "أخرى", "OTHER_DEFAULT"
    n = _norm_ar(raw)
    if n in _PDF_NORM:
        return _PDF_NORM[n], "PDF"
    alias = _ALIAS.get(n)
    if alias:
        return alias, "PDF"
    # غير موجود في PDF => Excel حرفيًا بدون آلية المطابقة
    return raw, "Excel"
